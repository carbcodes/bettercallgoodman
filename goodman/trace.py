"""Traceability: every checked result points to exactly one ChatGPT chat and prompt.

  python -m goodman.trace          check every task, write results/chats.md, exit 1 on a broken link

For each task it checks that the attempt the result was built from exists, that its prompt is
byte-identical to prompt.md, and (design tasks) that attempt_script.py is the code block from
that same attempt and part.step is what that script produces (by SHA-256 of the script).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:12]


def _attempts(d: Path) -> list[Path]:
    return sorted(d.glob("attempt*.json"), key=lambda p: (len(p.stem), p.stem))


def trace(d: Path) -> dict:
    prompt = (d / "prompt.md").read_text().rstrip("\n")
    result = json.loads((d / "result.json").read_text()) if (d / "result.json").exists() else None
    used = None
    if result and result.get("attempt"):
        used = d / result["attempt"]
    else:  # analysis tasks: the latest attempt with an answer
        with_answer = [p for p in _attempts(d) if json.loads(p.read_text()).get("answer")]
        used = with_answer[-1] if with_answer else None
    row = {"task": f"{d.parent.name}/{d.name}", "attempt": used.name if used else None, "chat_url": None,
           "model": None, "date": None, "outcome": (result or {}).get("outcome", "pending"), "problems": [],
           "script_sha": None, "others": [p.name for p in _attempts(d) if not used or p != used]}
    if used is None:
        if result:
            row["problems"].append("result.json exists but no attempt with an answer")
        tried = _attempts(d)
        if tried:  # stalled runs: still link the chat that was tried
            last = json.loads(tried[-1].read_text())
            row.update(chat_url=last.get("chat_url"), model=(last.get("model") or "").split(" (")[0],
                       date=last.get("date"), outcome="stalled (no answer)")
        return row
    a = json.loads(used.read_text())
    row.update(chat_url=a.get("chat_url"), model=(a.get("model") or "").split(" (")[0], date=a.get("date"))
    if a.get("prompt") != prompt:
        row["problems"].append("prompt in the attempt differs from prompt.md")
    if d.parent.name == "cad" and result:
        script = (d / "attempt_script.py").read_text() if (d / "attempt_script.py").exists() else None
        blocks = a.get("code") or []
        if script is None:
            row["problems"].append("no attempt_script.py")
        elif not any(script.rstrip() == b.rstrip() for b in blocks):
            row["problems"].append(f"attempt_script.py is not a code block of {used.name}")
        else:
            row["script_sha"] = _sha(script)
        if result.get("script_sha") and row["script_sha"] and result["script_sha"] != row["script_sha"]:
            row["problems"].append("result.json was made from a different script")
        if not a.get("chat_url"):
            row["problems"].append("no chat link for the attempt this part came from")
    return row


def main() -> int:
    rows = [trace(p.parent) for p in sorted(ROOT.glob("tasks/*/*/prompt.md"))]
    lines = ["# Chats", "",
             "Every checked result and the one ChatGPT conversation it came from. Generated by `python -m goodman.trace`.",
             "Analysis tasks (strength, collision) ran in temporary chats, which ChatGPT doesn't keep, so they have no link; "
             "their full prompt and answer are saved word for word in the attempt file.", "",
             "| Task | Outcome | Attempt | Chat | Model | Date | Script SHA-256 | Other attempts |",
             "|---|---|---|---|---|---|---|---|"]
    bad = 0
    for r in rows:
        chat = f"[open]({r['chat_url']})" if r["chat_url"] else ("temporary chat (text saved)" if r["attempt"] else "–")
        lines.append(f"| {r['task']} | {r['outcome']} | {r['attempt'] or '–'} | {chat} | {r['model'] or '–'} | "
                     f"{(r['date'] or '')[:16].replace('T', ' ')} | {r['script_sha'] or ''} | {', '.join(r['others'])} |")
        for p in r["problems"]:
            bad += 1
            print(f"{r['task']}: {p}")
    out = ROOT / "results" / "chats.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(rows)} tasks, {bad} problem(s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
